<?php

namespace App\Services\Scum;

use Illuminate\Support\Facades\DB;

/**
 * ??????? ??-??????? ????? ????? ?????????? ? ?????????? ???????????:
 * FTP-????? (scum:watch) ?????, RCON-????? (scum:rcon) ?????????.
 */
class ScumJobService
{
    /**
     * ????????? ?????? ? ??????? ? ????????? ??????????.
     * ??????????: 10 = Critical (???-???????), 5 = High (???-??????? !), 1 = Normal/Background.
     */
    public function enqueue(string $type, array $payload, int $priority = 1): int
    {
        return (int) DB::table('scum_jobs')->insertGetId([
            'type' => $type,
            'payload' => json_encode($payload, JSON_UNESCAPED_UNICODE),
            'status' => 'pending',
            'priority' => $priority,
            'created_at' => now(),
            'updated_at' => now(),
        ]);
    }

    /**
     * ??????? ???? ?????? ? ????????? ??????????? (??????? processing).
     * ??????????: priority DESC (??????? ??????), id ASC (FIFO ?????? ?????? ??????????).
     */
    public function claim(): ?array
    {
        return DB::transaction(function () {
            $job = DB::table('scum_jobs')
                ->where('status', 'pending')
                ->orderByDesc('priority')
                ->orderBy('id')
                ->lockForUpdate()
                ->first();
            if (! $job) {
                return null;
            }
            DB::table('scum_jobs')->where('id', $job->id)->update([
                'status' => 'processing',
                'updated_at' => now(),
            ]);
            $payload = $job->payload ? json_decode($job->payload, true) : null;

            return [
                'id' => $job->id,
                'type' => $job->type,
                'priority' => (int) ($job->priority ?? 1),
                'payload' => is_array($payload) ? $payload : [],
            ];
        });
    }

    public function done(int $id): void
    {
        DB::table('scum_jobs')->where('id', $id)->update([
            'status' => 'done',
            'updated_at' => now(),
        ]);
    }

    /**
     * ???????? ?????? ??????????? ? ????????? ????? (???????????? RCON-???????
     * ??? rcon_command ? ????? web-??????? ????? ????????? ?????????).
     */
    public function respond(int $id, ?string $response): void
    {
        DB::table('scum_jobs')->where('id', $id)->update([
            'status' => 'done',
            'response' => $response ?? '',
            'error' => null,
            'updated_at' => now(),
        ]);
    }

    public function fail(int $id, string $error): void
    {
        DB::table('scum_jobs')->where('id', $id)->update([
            'status' => 'error',
            'error' => substr($error, 0, 500),
            'updated_at' => now(),
        ]);
    }

    /**
     * ??????? ?????? ? ??????? pending ? ???????????? ????? RCON ??????????
     * ? ??????? ?? ????? ???? ????????? ??????, ?? ?????? ???? ?????.
     */
    public function requeue(int $id): void
    {
        DB::table('scum_jobs')->where('id', $id)->update([
            'status' => 'pending',
            'updated_at' => now(),
        ]);
    }

    public function pendingCount(): int
    {
        return (int) DB::table('scum_jobs')->where('status', 'pending')->count();
    }

    /** ???????? ?????? ?? id (??? ?????? ?????????? web-????????). */
    public function find(int $id): ?array
    {
        $job = DB::table('scum_jobs')->where('id', $id)->first();
        if (! $job) {
            return null;
        }

        return (array) $job;
    }

    /**
     * ?????? ???????????/??????????? ? ??????? ?????. ?????????? ?? RCON-??????
     * ?? ??????? ? ????? ??????? scum_jobs ?????? ??????????.
     */
    public function cleanupOld(int $maxAgeSeconds = 86400, int $keepRecent = 1000): int
    {
        $cutoff = now()->subSeconds($maxAgeSeconds)->toDateTimeString();

        return (int) DB::table('scum_jobs')
            ->whereIn('status', ['done', 'error'])
            ->where('updated_at', '<', $cutoff)
            ->where('id', '<=', function ($query) use ($keepRecent) {
                $query->selectRaw('COALESCE(MAX(id),0) - ?', [(int) $keepRecent])->from('scum_jobs');
            })
            ->delete();
    }
}
